    private static int MapTaminPrescriptionType(int internalPrescType)
        => internalPrescType switch
        {
            1 => 1, // دارو
            2 => 2, // پاراکلینیک
            3 => 2, // تصویربرداری فعلاً پاراکلینیک
            4 => 2, // فیزیوتراپی فعلاً پاراکلینیک/تا تکمیل سرویس اختصاصی
            _ => 0
        };

    private static string MapDefaultSrvType(int internalPrescType)
        => internalPrescType switch
        {
            1 => "01",
            2 => "02",
            3 => "03",
            4 => "13",
            _ => ""
        };

    private static string? ToTaminDate(string? sdate)
    {
        if (string.IsNullOrWhiteSpace(sdate)) return null;
        var d = sdate.Trim();
        if (d.Length >= 10) d = d[..10];
        return d.Replace("/", "");
    }

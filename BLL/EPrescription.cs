    }

    private static IEnumerable<EPrescriptionBaseCatalog> ExtractCatalogItems(string rawJson, string catalogType)
    {
        JsonNode? root;
        try { root = JsonNode.Parse(rawJson); }
        catch { yield break; }
        if (root == null) yield break;

        var arrays = new List<JsonArray>();
        if (root is JsonArray rootArray) arrays.Add(rootArray);
        if (root is JsonObject obj)
        {
            foreach (var key in new[] { "data", "list", "items", "result", "content", "rows" })
                if (obj[key] is JsonArray childArray) arrays.Add(childArray);
        }

        foreach (var arr in arrays)
        {
            foreach (var node in arr)
            {
                if (node is not JsonObject item) continue;
                var code = FirstString(item, "code", "id", "ID", "srvCode", "serviceCode", "drugCode", "drugAmntId", "drugInstId", "parGrpCode");
                var name = FirstString(item, "name", "title", "Name", "desc", "description", "serviceName", "drugName", "caption");
                var type = FirstString(item, "type", "srvType", "serviceType", "category");
                if (string.IsNullOrWhiteSpace(code) && string.IsNullOrWhiteSpace(name)) continue;
                yield return new EPrescriptionBaseCatalog
                {
                    ProviderCode = ProviderTamin,
                    CatalogType = catalogType,
                    ItemCode = code ?? string.Empty,
                    ItemName = name ?? string.Empty,
                    ItemType = type ?? string.Empty,
                    RawJson = item.ToJsonString(),
                    IsActive = true
                };
            }
        }
    }

    private static string? FirstString(JsonObject obj, params string[] keys)
    {
        foreach (var key in keys)
        {
            if (obj.TryGetPropertyValue(key, out var node) && node != null)
                return node.ToString();
        }
        return null;
    }


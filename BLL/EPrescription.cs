    public EPrescriptionBuildResult BuildTaminPrescriptionDraft(
        Models.Enc enc,
        Models.DrPrescription prescription,
        List<DrPrescriptionItem> items,
        int prescType,
        int userPersID)
    {
        var result = new EPrescriptionBuildResult { ProviderCode = ProviderTamin };

        if (enc == null || enc.EncID <= 0)
            result.Errors.Add("پذیرش/بیمار جاری مشخص نیست.");
        if (string.IsNullOrWhiteSpace(enc?.NationalCode))
            result.Errors.Add("کد ملی بیمار برای ارسال نسخه الکترونیک لازم است.");
        if (items == null || items.Count == 0)
            result.Errors.Add("نسخه فاقد آیتم است.");

        var setting = LoadProviderSetting(ProviderTamin);
        if (setting.ProviderID == 0)
            result.Warnings.Add("تنظیمات Provider تامین اجتماعی هنوز ثبت نشده است؛ خروجی فعلاً Draft/Mock است.");

        var taminPrescType = MapTaminPrescriptionType(prescType);
        if (taminPrescType == 0)
            result.Errors.Add($"نوع نسخه داخلی {prescType} هنوز برای تامین اجتماعی Map نشده است.");

        var detailList = new List<object>();
        if (items != null)
        {
            foreach (var item in items.Where(x => x.CRUD != 3))
            {
                var map = LoadServiceMap(ProviderTamin, item.ItemID);
                if (map.MapID == 0)
                {
                    result.Warnings.Add($"برای آیتم '{item.ItemName}' با ItemID={item.ItemID} نگاشت کد تامین اجتماعی ثبت نشده است.");
                }

                var detail = new Dictionary<string, object?>
                {
                    ["srvId"] = new Dictionary<string, object?>
                    {
                        ["srvCode"] = string.IsNullOrWhiteSpace(map.ProviderSrvCode) ? $"MISSING_MAP_{item.ItemID}" : map.ProviderSrvCode,
                        ["srvType"] = new Dictionary<string, object?>
                        {
                            ["srvType"] = string.IsNullOrWhiteSpace(map.ProviderSrvType) ? MapDefaultSrvType(prescType) : map.ProviderSrvType
                        }
                    },
                    ["srvQty"] = item.Num <= 0 ? 1 : item.Num
                };

                if (!string.IsNullOrWhiteSpace(map.ProviderTerminology))
                    ((Dictionary<string, object?>)detail["srvId"]!)["terminology"] = map.ProviderTerminology;
                if (!string.IsNullOrWhiteSpace(map.ProviderParTarefGrp))
                    ((Dictionary<string, object?>)detail["srvId"]!)["parTarefGrp"] = new Dictionary<string, object?> { ["parGrpCode"] = map.ProviderParTarefGrp };

                if (prescType == 1)
                {
                    if (item.UseTime > 0)
                        detail["timesAday"] = new Dictionary<string, object?> { ["drugAmntId"] = item.UseTime };
                    if (item.UseDose > 0)
                        detail["drugInstruction"] = new Dictionary<string, object?> { ["drugInstId"] = item.UseDose };
                    if (!string.IsNullOrWhiteSpace(item.Note))
                        detail["dose"] = item.Note;
                }
                else if (!string.IsNullOrWhiteSpace(item.Note))
                {
                    detail["dose"] = item.Note;
                }

                detailList.Add(detail);
            }
        }

        var request = new Dictionary<string, object?>
        {
            ["patient"] = enc?.NationalCode?.Trim(),
            ["mobile"] = enc?.Mobile,
            ["prescDate"] = ToTaminDate(prescription?.Date2),
            ["expireDate"] = null,
            ["docId"] = "",
            ["docNationalCode"] = "",
            ["docMobileNo"] = "",
            ["prescType"] = new Dictionary<string, object?> { ["prescTypeId"] = taminPrescType },
            ["comments"] = "Generated by Saman HIS - draft",
            ["clientId"] = setting.IsTestMode ? "" : null,
            ["noteDetailEprscs"] = detailList
        };

        var options = new JsonSerializerOptions
        {
            WriteIndented = true,
            Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping
        };
        result.RequestJson = JsonSerializer.Serialize(request, options);
        result.IsValid = result.Errors.Count == 0;
        return result;
    }


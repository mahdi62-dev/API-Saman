    public string GenerateCodeVerifier(int length = 64)
    {
        const string chars = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-._~";
        length = Math.Clamp(length, 43, 128);
        var bytes = RandomNumberGenerator.GetBytes(length);
        var result = new char[length];
        for (var i = 0; i < length; i++)
            result[i] = chars[bytes[i] % chars.Length];
        return new string(result);
    }

    public string GenerateCodeChallenge(string codeVerifier)
    {
        var bytes = System.Text.Encoding.ASCII.GetBytes(codeVerifier ?? string.Empty);
        var hash = SHA256.HashData(bytes);
        return Base64UrlEncode(hash);
    }

    public string BuildTaminAuthorizeUrl(bool isTest, string redirectUri, string clientId, string codeChallenge, string state)
    {
        var baseUrl = isTest
            ? "https://account-pilot.tamin.ir/auth/server/authorize"
            : "https://account.tamin.ir/auth/server/authorize";

        var q = new Dictionary<string, string?>
        {
            ["redirect_uri"] = redirectUri,
            ["response_type"] = "code",
            ["client_id"] = clientId,
            ["code_challenge"] = codeChallenge,
            ["code_challenge_method"] = "S256",
            ["state"] = state
        };

        return baseUrl + "?" + string.Join("&", q.Select(x => Uri.EscapeDataString(x.Key) + "=" + Uri.EscapeDataString(x.Value ?? string.Empty)));
    }

    public async Task<EPrescriptionTokenResult> ExchangeTaminAuthorizationCodeAsync(bool isTest, string redirectUri, string clientId, string code, string codeVerifier, string audience, bool useV2 = true)
    {
        var tokenUrl = isTest
            ? (useV2 ? "https://account-pilot.tamin.ir/auth/server/v2/token" : "https://account-pilot.tamin.ir/auth/server/token")
            : (useV2 ? "https://account.tamin.ir/auth/server/v2/token" : "https://account.tamin.ir/auth/server/token");

        var form = new List<KeyValuePair<string, string>>
        {
            new("redirect_uri", redirectUri ?? string.Empty),
            new("grant_type", "authorization_code"),
            new("client_id", clientId ?? string.Empty),
            new("code", code ?? string.Empty),
            new("code_verifier", codeVerifier ?? string.Empty)
        };

        if (useV2 && !string.IsNullOrWhiteSpace(audience))
            form.Add(new KeyValuePair<string, string>("audience", audience));

        using var http = new HttpClient { Timeout = TimeSpan.FromSeconds(90) };
        using var content = new FormUrlEncodedContent(form);
        var response = await http.PostAsync(tokenUrl, content);
        var raw = await response.Content.ReadAsStringAsync();

        var result = new EPrescriptionTokenResult { RawJson = raw, IsSuccess = response.IsSuccessStatusCode };
        if (!response.IsSuccessStatusCode)
        {
            result.ErrorMessage = $"HTTP {(int)response.StatusCode} {response.ReasonPhrase}\n{raw}";
            return result;
        }

        try
        {
            var json = JsonNode.Parse(raw)?.AsObject();
            result.AccessToken = json?["access_token"]?.ToString() ?? string.Empty;
            result.RefreshToken = json?["refresh_token"]?.ToString() ?? string.Empty;
            if (int.TryParse(json?["expires_in"]?.ToString(), out var expires)) result.ExpiresIn = expires;
            result.IsSuccess = !string.IsNullOrWhiteSpace(result.AccessToken);
            if (!result.IsSuccess) result.ErrorMessage = "Token response does not contain access_token.";
        }
        catch (Exception ex)
        {
            result.IsSuccess = false;
            result.ErrorMessage = ex.Message;
        }

        return result;
    }

    private static string Base64UrlEncode(byte[] bytes)
    {
        return Convert.ToBase64String(bytes)
            .TrimEnd('=')
            .Replace('+', '-')
            .Replace('/', '_');
    }

        public async Task<string> FetchTaminBaseCatalogAsync(string url, string bearerToken, string? serviceType = null)
    {
        if (string.IsNullOrWhiteSpace(url))
            throw new ArgumentException("Base service URL is empty.");
        if (string.IsNullOrWhiteSpace(bearerToken))
            throw new ArgumentException("Bearer token is empty.");

        var finalUrl = url.Replace("{SERVICE_TYPE}", serviceType ?? string.Empty)
                          .Replace("[SERVICE_TYPE]", serviceType ?? string.Empty);

        using var http = new HttpClient { Timeout = TimeSpan.FromSeconds(90) };
        http.DefaultRequestHeaders.Authorization = new AuthenticationHeaderValue("Bearer", bearerToken.Trim());
        http.DefaultRequestHeaders.Accept.Add(new MediaTypeWithQualityHeaderValue("application/json"));

        var response = await http.GetAsync(finalUrl);
        var body = await response.Content.ReadAsStringAsync();
        if (!response.IsSuccessStatusCode)
            throw new Exception($"HTTP {(int)response.StatusCode} {response.ReasonPhrase}\n{body}");

        return body;
    }

    public int SaveTaminBaseCatalogRaw(string catalogType, string rawJson, int userPersID)
    {
        if (string.IsNullOrWhiteSpace(rawJson)) return 0;

        EnsureBaseCatalogTable();
        var items = ExtractCatalogItems(rawJson, catalogType).ToList();
        if (items.Count == 0)
            items.Add(new EPrescriptionBaseCatalog
            {
                ProviderCode = ProviderTamin,
                CatalogType = catalogType,
                ItemCode = "RAW",
                ItemName = catalogType,
                ItemType = "RAW",
                RawJson = rawJson,
                IsActive = true,
                UserPersID = userPersID
            });

        const string disableSql = @"
UPDATE SamanHIS.dbo.EPrescriptionBaseCatalog
   SET IsActive = 0
 WHERE ProviderCode = @ProviderCode
   AND CatalogType = @CatalogType";
        var disableCom = new SqlCommand();
        disableCom.Parameters.AddWithValue("@ProviderCode", ProviderTamin);
        disableCom.Parameters.AddWithValue("@CatalogType", catalogType ?? "");
        new DataService().ExecuteNonQueryByText(CSet.cnStringHIS, disableCom, disableSql);

        const string insertSql = @"
DECLARE @Now NCHAR(16);
SELECT @Now = SamanHIS.dbo.SCurdatetime();
INSERT INTO SamanHIS.dbo.EPrescriptionBaseCatalog
(ProviderCode, CatalogType, ItemCode, ItemName, ItemType, RawJson, IsActive, UserPersID, ActionDate)
VALUES
(@ProviderCode, @CatalogType, @ItemCode, @ItemName, @ItemType, @RawJson, 1, @UserPersID, @Now);";

        foreach (var item in items)
        {
            var com = new SqlCommand();
            com.Parameters.AddWithValue("@ProviderCode", ProviderTamin);
            com.Parameters.AddWithValue("@CatalogType", catalogType ?? "");
            com.Parameters.AddWithValue("@ItemCode", (object?)item.ItemCode ?? DBNull.Value);
            com.Parameters.AddWithValue("@ItemName", (object?)item.ItemName ?? DBNull.Value);
            com.Parameters.AddWithValue("@ItemType", (object?)item.ItemType ?? DBNull.Value);
            com.Parameters.AddWithValue("@RawJson", rawJson);
            com.Parameters.AddWithValue("@UserPersID", userPersID);
            new DataService().ExecuteNonQueryByText(CSet.cnStringHIS, com, insertSql);
        }

        return items.Count;
    }

